#!/usr/bin/env python3
"""Package the canonical core into two fixed plugin contexts; never install it."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import sys
import tempfile

CONTEXTS = (
    Path("plugins/delegated-intelligence/context"),
    Path("plugins/verify-before-claim/context"),
)


def simple_path(root: Path, path: Path) -> None:
    """Refuse link/junction redirection and writes outside the selected repository."""
    if not path.resolve().is_relative_to(root):
        raise ValueError(f"path escapes repository: {path}")
    for part in (path, *path.parents):
        if part == root:
            break
        if part.is_symlink() or getattr(part, "is_junction", lambda: False)():
            raise ValueError(f"linked source/output path is not supported: {part}")
        if part != path and part.exists() and not part.is_dir():
            raise ValueError(f"parent is not a directory: {part}")
    if path.exists() and not path.is_file():
        raise ValueError(f"expected a regular file: {path}")


def unique_keys(pairs: list[tuple[str, object]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate ownership key: {key}")
        result[key] = value
    return result


def projections(root: Path) -> list[tuple[Path, bytes]]:
    source_paths = [root / "core" / name for name in ("OPERATING.md", "ownership.json")]
    for path in source_paths:
        simple_path(root, path)
    policy, index = [path.read_bytes() for path in source_paths]
    if not policy.decode("utf-8").strip():
        raise ValueError("OPERATING.md must contain the canonical policy")
    registry = json.loads(index.decode("utf-8"), object_pairs_hook=unique_keys)
    if (not isinstance(registry, dict) or type(registry.get("schemaVersion")) is not int
            or registry["schemaVersion"] != 1):
        raise ValueError("ownership.json must declare schemaVersion 1")
    header = (
        "<!-- GENERATED by core/sync.py; DO NOT EDIT.\n"
        f"core/OPERATING.md sha256: {hashlib.sha256(policy).hexdigest()}\n"
        f"core/ownership.json sha256: {hashlib.sha256(index).hexdigest()}\n"
        "Edit the canonical sources, then run python core/sync.py.\n"
        "This packages selected-method dependencies; always-on adoption requires\n"
        "approved host instructions. The index names repository owners, not\n"
        "capabilities proven installed in this host.\n-->\n\n"
    ).encode("utf-8")
    outputs = [(root / context / name, content) for context in CONTEXTS
               for name, content in (("OPERATING.md", header + policy), ("ownership.json", index))]
    # Preflight all four paths before changing any file.
    for path, _ in outputs:
        simple_path(root, path)
    return outputs


def atomic_write(path: Path, content: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, name = tempfile.mkstemp(prefix=".core-sync-", dir=path.parent)
    temporary = Path(name)
    try:
        with os.fdopen(descriptor, "wb") as output:
            output.write(content)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        if not root.is_dir():
            raise ValueError(f"repository root is not a directory: {root}")
        outputs = projections(root)
        drift = [(path, content) for path, content in outputs
                 if not path.is_file() or path.read_bytes() != content]
        if args.check:
            for path, _ in drift:
                print(f"DRIFT {path.relative_to(root).as_posix()}")
            if drift:
                return 1
            print("core projections: 4 files in sync")
        else:
            for path, content in drift:
                atomic_write(path, content)
            print(f"core projections: 4 checked, {len(drift)} updated")
        return 0
    except (OSError, ValueError) as error:
        print(f"core sync: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
