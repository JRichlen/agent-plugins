#!/usr/bin/env bash
# evals/paid/subject-matrix.sh — run one behavioral pack against extra subject
# models (issue #102, measurement 1) without editing the pack.
#
# The pack's promptfooconfig.yaml pins ONE subject provider. This script writes
# a sibling overlay, promptfooconfig.matrix.yaml, that keeps the baseline
# provider first and appends each requested subject with the baseline's own
# per-provider config (max_tokens, showThinking, ...) so every subject is graded
# under identical settings. Nothing in the pack is modified; the overlay is
# ignored by git and by the required behavioral leg.
#
# Usage:
#   subject-matrix.sh PACK_DIR --subjects "id1,id2"        # write the overlay, print its path
#   subject-matrix.sh PACK_DIR --baseline-id               # print the pack's baseline provider id
#   subject-matrix.sh --self-test                          # offline fixture; non-zero on failure
#
# Requires PyYAML (present on GitHub's ubuntu runners and in this repo's dev
# environments). Absent PyYAML it exits 3 and says so — never a silent skip.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

py() { python3 - "$@" <<'PY'
import sys, os, json
try:
    import yaml
except Exception:
    print("subject-matrix: PyYAML is not available; cannot read the pack config (exit 3)", file=sys.stderr); sys.exit(3)
mode = sys.argv[1]
if mode == "--self-test":
    import tempfile
    d = tempfile.mkdtemp()
    cfg = {"description": "fixture", "prompts": ["file://prompt.txt"],
           "providers": [{"id": "openrouter:base/model", "config": {"max_tokens": 8192, "showThinking": False}}],
           "evaluateOptions": {"repeat": 3}, "defaultTest": {"vars": {"skill": "x"}}, "tests": [{"description": "s1"}]}
    yaml.safe_dump(cfg, open(os.path.join(d, "promptfooconfig.yaml"), "w"), sort_keys=False)
    sys.argv = [sys.argv[0], d, "--subjects", "anthropic:messages:claude-haiku-4-5-20251001, openrouter:other/model,openrouter:base/model"]
    mode = d
pack = mode
USAGE = "usage: subject-matrix.sh PACK_DIR --subjects \"id1,id2\" | PACK_DIR --baseline-id | --self-test"
if len(sys.argv) < 3 or sys.argv[2] not in ("--subjects", "--baseline-id"):
    print(f"subject-matrix: {USAGE}", file=sys.stderr); sys.exit(2)
if sys.argv[2] == "--subjects" and (len(sys.argv) < 4 or not sys.argv[3].strip()):
    print("subject-matrix: --subjects needs a comma-separated list of provider ids", file=sys.stderr); sys.exit(2)
src = os.path.join(pack, "promptfooconfig.yaml")
if not os.path.isfile(src):
    print(f"subject-matrix: no promptfooconfig.yaml in {pack}", file=sys.stderr); sys.exit(2)
cfg = yaml.safe_load(open(src))
provs = cfg.get("providers") or []
if not provs:
    print(f"subject-matrix: {src} declares no providers", file=sys.stderr); sys.exit(2)
base = provs[0]
base_id = base.get("id") if isinstance(base, dict) else str(base)
base_cfg = (base.get("config") if isinstance(base, dict) else None) or {}
if sys.argv[2] == "--baseline-id":
    print(base_id); sys.exit(0)
subjects = [s.strip() for s in sys.argv[3].split(",") if s.strip()]
subjects = [s for s in subjects if s != base_id]
if not subjects:
    print("subject-matrix: no subjects besides the baseline; nothing to overlay", file=sys.stderr); sys.exit(2)
overlay = dict(cfg)
overlay["providers"] = [base] + [{"id": s, "config": json.loads(json.dumps(base_cfg))} for s in subjects]
out = os.path.join(pack, "promptfooconfig.matrix.yaml")
with open(out, "w") as f:
    f.write("# GENERATED by evals/paid/subject-matrix.sh — the baseline provider first, then each\n"
            "# extra subject with the baseline's own config. Not committed; not used by the required leg.\n")
    yaml.safe_dump(overlay, f, sort_keys=False, allow_unicode=True)
if os.environ.get("SUBJECT_MATRIX_SELF_TEST") == "1":
    back = yaml.safe_load(open(out))
    ids = [p["id"] for p in back["providers"]]
    assert ids == ["openrouter:base/model", "anthropic:messages:claude-haiku-4-5-20251001", "openrouter:other/model"], ids
    assert all(p["config"] == {"max_tokens": 8192, "showThinking": False} for p in back["providers"]), back["providers"]
    assert back["evaluateOptions"] == {"repeat": 3} and back["tests"] == [{"description": "s1"}]
    print("subject-matrix self-test: overlay keeps the baseline first, copies its config to every subject, drops a duplicate of the baseline, and leaves the rest of the pack untouched")
    sys.exit(0)
print(out)
PY
}

case "${1:-}" in
  --self-test) SUBJECT_MATRIX_SELF_TEST=1 py --self-test ;;
  "" ) echo "usage: subject-matrix.sh PACK_DIR --subjects \"id1,id2\" | PACK_DIR --baseline-id | --self-test" >&2; exit 2 ;;
  *) py "$@" ;;
esac
