#!/usr/bin/env python3
"""bin/generate.py — emits configs/generated/<plugin>.yaml for all 25
marketplace plugins (T46, design §7.4).

Python 3.12 standard library only.

    python3 evals/redteam/bin/generate.py --write     # emit configs/generated/**
    python3 evals/redteam/bin/generate.py --check      # regenerate to a temp dir,
                                                          # diff, exit 1 on drift

For each plugin, ONE promptfooconfig with the complete 2x2 (design §7.1):
three providers (`baseline`, `baseline-generic`, `treatment` -- distinct
`file://` ids so promptfoo never pools the arms, §7.3) crossed with 32 test
rows (16 clean, 16 adversarial corpus items) and `evaluateOptions.repeat: 3`,
giving the six cells C1-C6 (3 arms x 2 conditions) and 288 planned attempts
per plugin -- 7200 across all 25.

What differs between the three arms lives ENTIRELY in each provider's
`config.skillPath` (null / targets/generic-guidance.md / this plugin's real
SKILL.md), read at request time by providers/lib/transcript.js inside
target-textual.js. The 32 test rows themselves -- the frozen corpus item plus
this plugin's task/artifact/sandbox_root/canary_secret/guards from
targets/plugins.json -- are IDENTICAL across all three providers, because
promptfoo cross-products one `tests:` list against all `providers:`. That is
what makes the parity claim structural rather than asserted: there is only
one test-row array per plugin, not three hand-synced copies.

NO model-graded assertion anywhere in this output (design §7.4/§8.1): the
three deterministic assertions (protected-effect, effect-line, task-completed)
each carry weight 1 and `threshold: 1`; the advisory rubric exists only in the
approval-gated configs/paid/rubric-overlay.yaml, which nothing here names.

Every corpus item is read ONLY through freeze.load() (never a raw path), so a
frozen-corpus hash mismatch fails generation rather than silently emitting
stale content -- the same discipline bin/render_controls.py already uses for
T45's offline form.
"""
